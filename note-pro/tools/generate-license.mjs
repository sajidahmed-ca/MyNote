/**
 * MyNote Pro — License key generator (CLI)
 *
 * Generates signed Ed25519 license keys for the Pro app.
 * The Pro app ships only the PUBLIC key, so keys can be verified
 * on-device without a server. Keep the private key safe.
 *
 * Usage:
 *   npm run license -- --name "Sajid Karim" --email "sajid@example.com" --days 365
 *   npm run license -- --name "Sajid Karim" --email "sajid@example.com" --lifetime
 *
 * Keys are written to keys/. The public key is embedded into
 * src/lib/licensePublicKey.js automatically on first run.
 */
import {
  createPublicKey,
  generateKeyPairSync,
  randomUUID,
  sign,
} from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const projectRoot = join(root, '..')
const keysDir = join(projectRoot, 'keys')
const privatePath = join(keysDir, 'license_private.pem')
const publicPath = join(keysDir, 'license_public.pem')
const keyIdPath = join(keysDir, 'key_id')
const publicKeyModule = join(projectRoot, 'src', 'lib', 'licensePublicKey.js')

const arg = (flag) => {
  const i = process.argv.indexOf(flag)
  return i > -1 ? process.argv[i + 1] : undefined
}

const b64url = (buf) => Buffer.from(buf).toString('base64url')

function ensureKeyPair() {
  if (existsSync(privatePath) && existsSync(publicPath)) {
    return {
      privatePem: readFileSync(privatePath, 'utf8'),
      publicPem: readFileSync(publicPath, 'utf8'),
      keyId: existsSync(keyIdPath) ? readFileSync(keyIdPath, 'utf8') : randomUUID(),
    }
  }

  mkdirSync(keysDir, { recursive: true })
  writeFileSync(keyIdPath, randomUUID())
  const { publicKey, privateKey } = generateKeyPairSync('ed25519')
  writeFileSync(privatePath, privateKey.export({ type: 'pkcs8', format: 'pem' }))
  writeFileSync(publicPath, publicKey.export({ type: 'spki', format: 'pem' }))

  console.log('[license] Generated new Ed25519 key pair in keys/')
  console.log('[license] Keep license_private.pem secret. Never ship it.')
  console.log('')

  return {
    privatePem: readFileSync(privatePath, 'utf8'),
    publicPem: readFileSync(publicPath, 'utf8'),
    keyId: readFileSync(keyIdPath, 'utf8'),
  }
}

function publicRawBytes(pem) {
  const key = createPublicKey(pem)
  const spki = key.export({ type: 'spki', format: 'der' })
  return spki.subarray(spki.length - 32)
}

function embedPublicKey({ publicPem, keyId }) {
  const raw = publicRawBytes(publicPem)
  const content = `// Auto-generated by tools/generate-license.mjs — do not edit by hand.
export const LICENSE_KEY_ID = '${keyId}'

export const LICENSE_PUBLIC_KEY_B64 = '${raw.toString('base64')}'
`
  writeFileSync(publicKeyModule, content)
  console.log('[license] Public key embedded in src/lib/licensePublicKey.js')
}

function buildLicense({ name, email, plan, issuedAt, expiresAt, privatePem }) {
  const payload = { id: randomUUID(), name, email, plan, issuedAt, expiresAt }
  const payloadB64 = b64url(Buffer.from(JSON.stringify(payload)))
  const signatureB64 = b64url(sign(null, Buffer.from(payloadB64), privatePem))
  return { payloadB64, signatureB64 }
}

function main() {
  const name = arg('--name')
  const email = arg('--email')
  const plan = arg('--plan') || 'pro'

  if (!name || !email) {
    console.error(
      'Usage: npm run license -- --name "<Name>" --email "<Email>" [--days N | --lifetime]',
    )
    process.exit(1)
  }

  const issuedAt = Date.now()
  const lifetime = process.argv.includes('--lifetime')
  const days = lifetime ? null : Number(arg('--days')) || 365
  const expiresAt = lifetime ? null : issuedAt + days * 86_400_000

  const { privatePem, publicPem, keyId } = ensureKeyPair()
  embedPublicKey({ publicPem, keyId })

  const { payloadB64, signatureB64 } = buildLicense({
    name,
    email,
    plan,
    issuedAt,
    expiresAt,
    privatePem,
  })

  const licenseKey = `v1.${keyId}.${payloadB64}.${signatureB64}`

  const label = name.replace(/\s+/g, '-').toLowerCase()
  const outPath = join(keysDir, `${label}-license.txt`)
  writeFileSync(
    outPath,
    `${licenseKey}\n\nIssued for: ${name} <${email}> ${
      lifetime ? '(lifetime)' : `(${days} days until ${new Date(expiresAt).toISOString().slice(0, 10)})`
    }`,
  )

  console.log('')
  console.log('┌─────────────────────────────────────────────────────────')
  console.log('│  MyNote Pro — License key')
  console.log('├─────────────────────────────────────────────────────────')
  console.log(`│  Name      ${name}`)
  console.log(`│  Email     ${email}`)
  console.log(`│  Plan      ${plan}`)
  console.log(
    `│  Expires   ${lifetime ? 'never (lifetime)' : new Date(expiresAt).toISOString().slice(0, 10)}`,
  )
  console.log('└─────────────────────────────────────────────────────────')
  console.log('')
  console.log(licenseKey)
  console.log('')
  console.log(`Saved to ${outPath}`)
  console.log('Paste this key into the Pro app → Activate.')
}

main()